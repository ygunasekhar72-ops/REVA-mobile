'use strict';
/* Regenerate js/modeldb-data.js — the bundled models.dev snapshot.
   Source: models.dev (MIT, https://models.dev). The trim logic here is
   kept in sync with js/modeldb.js trim() (asserted by tests/modeldb.test.js).

   Usage:
     node scripts/gen-modeldb.js < path/to/api.json    # offline, JSON on stdin
     node scripts/gen-modeldb.js --fetch               # fetch https://models.dev/api.json
*/
const fs = require('fs');
const path = require('path');
const ROOT = __dirname.slice(0, __dirname.lastIndexOf(path.sep)); // repo root, no '..' literals

/* compact map REVA needs: { gen, m: { '<lowercased id>': [contextTokens, flags] } }
   flags: 1=vision(image input) 2=tool_call 4=reasoning 8=attachment.
   KEEP IN SYNC with js/modeldb.js trim(). */
function trim(apiJson) {
  var out = { gen: new Date().toISOString().slice(0, 10), m: {} };
  var provs = apiJson && typeof apiJson === 'object' ? apiJson : {};
  Object.keys(provs).forEach(function (pk) {
    var models = provs[pk] && provs[pk].models;
    if (!models) return;
    Object.keys(models).forEach(function (id) {
      var mod = models[id];
      if (!mod || !mod.id) return;
      var ctx = (mod.limit && mod.limit.context) || 0;
      var input = (mod.modalities && mod.modalities.input) || [];
      var flags = 0;
      if (input.indexOf('image') >= 0) flags |= 1;
      if (mod.tool_call) flags |= 2;
      if (mod.reasoning) flags |= 4;
      if (mod.attachment) flags |= 8;
      var key = String(mod.id).toLowerCase().trim();
      if (!out.m[key]) out.m[key] = [ctx, flags];
      var tail = key.split('/').pop();
      if (tail && tail !== key && !out.m[tail]) out.m[tail] = [ctx, flags];
    });
  });
  return out;
}

function emit(json) {
  const t = trim(json);
  const out = '/* REVA model metadata snapshot — generated by scripts/gen-modeldb.js\n' +
    '   from https://models.dev/api.json (MIT) on ' + t.gen + '. DO NOT EDIT;\n' +
    '   regenerate instead. See THIRD_PARTY_NOTICES.md for attribution. */\n' +
    'window.REVAMODELDB_DATA = ' + JSON.stringify(t) + ';\n';
  const dest = path.join(ROOT, 'js', 'modeldb-data.js');
  if (!dest.startsWith(ROOT + path.sep)) throw new Error('output path escaped repo root');
  fs.writeFileSync(dest, out);
  console.log('modeldb-data.js written: ' + Object.keys(t.m).length + ' model ids, ' +
    (fs.statSync(dest).size / 1024).toFixed(0) + ' KB, snapshot ' + t.gen);
}

if (process.argv[2] === '--fetch') {
  fetch('https://models.dev/api.json', { cache: 'no-store' })
    .then(r => r.json())
    .then(emit)
    .catch(e => { console.error('gen-modeldb failed: ' + e.message); process.exit(1); });
} else {
  emit(JSON.parse(fs.readFileSync(0, 'utf8'))); // models.dev JSON on stdin — no path handling
}
