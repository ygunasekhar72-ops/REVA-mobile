/* REVA — model metadata registry (runtime).
   Data source: models.dev (MIT, https://models.dev) — the open model
   database maintained by the opencode team. A trimmed snapshot ships in
   js/modeldb-data.js (generated by scripts/gen-modeldb.js); this runtime
   also accepts a fresher snapshot cached in localStorage by refresh().
   Lookup is by model id (case-insensitive, with last-path-segment alias
   so 'nvidia/llama-3.3-70b' matches 'llama-3.3-70b' too).
   Works in the browser (window.REVAMODELDB) and in node (module.exports)
   so the generator and the unit tests share this exact logic. */
(function (root, factory) {
  var api = factory(root.REVAMODELDB_DATA || null);
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.REVAMODELDB = api;
})(typeof window !== 'undefined' ? window : global, function (snapshot) {
  'use strict';
  var LS_KEY = 'reva.modeldb.cache';
  var data = snapshot || { gen: '', m: {} };

  /* adopt a fresher snapshot cached by refresh() (string ISO date compare) */
  try {
    var cached = localStorage.getItem(LS_KEY);
    if (cached) {
      var c = JSON.parse(cached);
      if (c && c.gen && data.gen && String(c.gen) > String(data.gen)) data = c;
      else if (c && c.gen && !data.gen) data = c;
    }
  } catch (e) { /* offline/private-mode — bundled snapshot stands */ }

  /* trim the full models.dev api.json to the compact map REVA needs:
     { gen, m: { '<lowercased id>': [contextTokens, flags] } }
     flags: 1=vision(image input) 2=tool_call 4=reasoning 8=attachment.
     Last path segment ('llama-3.3-70b' of 'meta/llama-3.3-70b') is aliased
     to the same entry — first writer wins for cross-provider duplicates. */
  function trim(apiJson) {
    var out = { gen: new Date().toISOString().slice(0, 10), m: {} };
    var provs = apiJson && typeof apiJson === 'object' ? apiJson : {};
    Object.keys(provs).forEach(function (pk) {
      var models = provs[pk] && provs[pk].models;
      if (!models) return;
      Object.keys(models).forEach(function (id) {
        var mod = models[id];
        if (!mod || !mod.id) return;
        var ctx = (mod.limit && mod.limit.context) || 0;
        var input = (mod.modalities && mod.modalities.input) || [];
        var flags = 0;
        if (input.indexOf('image') >= 0) flags |= 1;
        if (mod.tool_call) flags |= 2;
        if (mod.reasoning) flags |= 4;
        if (mod.attachment) flags |= 8;
        var key = String(mod.id).toLowerCase().trim();
        if (!out.m[key]) out.m[key] = [ctx, flags];
        var tail = key.split('/').pop();
        if (tail && tail !== key && !out.m[tail]) out.m[tail] = [ctx, flags];
      });
    });
    return out;
  }

  function setData(snap) { data = snap || { gen: '', m: {} }; }
  function gen() { return data.gen || ''; }
  function size() { return Object.keys(data.m || {}).length; }

  function lookup(model) {
    var k = String(model || '').toLowerCase().trim();
    if (!k) return null;
    var hit = (data.m || {})[k];
    if (!hit) {
      var tail = k.split('/').pop();
      if (tail && tail !== k) hit = (data.m || {})[tail];
    }
    if (!hit) return null;
    return {
      ctx: hit[0] || 0,
      vision: !!(hit[1] & 1),
      tools: !!(hit[1] & 2),
      reasoning: !!(hit[1] & 4),
      attachment: !!(hit[1] & 8)
    };
  }

  /* silent background refresh; never throws into the caller */
  function refresh() {
    if (typeof fetch === 'undefined') return Promise.resolve(0);
    return fetch('https://models.dev/api.json', { cache: 'no-store' })
      .then(function (r) { return r.json(); })
      .then(function (j) {
        var t = trim(j);
        try { localStorage.setItem(LS_KEY, JSON.stringify(t)); } catch (e) { /* quota — bundled data stands */ }
        data = t;
        return size();
      });
  }

  return { lookup: lookup, gen: gen, size: size, trim: trim, setData: setData, refresh: refresh };
});
